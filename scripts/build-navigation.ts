import { createHash } from 'node:crypto';
import fs from 'node:fs';
import * as THREE from 'three';
import { BaseGrid } from '../apps/web/src/game/BaseGrid';
import { CropSystem } from '../apps/web/src/game/Crops';
import { type BaseFullLayout, mapTransform } from '../packages/shared/src/navigation';
import { readGeometry } from './read-geometry';

const bases: Record<string, unknown> = {};
const hash = createHash('sha256');
const plants = readGeometry('Assets/bases/plantas.glb');
const terrain = readGeometry('Assets/bases/terreno.glb');
for (const source of [
  'packages/shared/src/navigation.ts',
  'packages/shared/src/movement.ts',
  'apps/web/src/game/BaseGrid.ts',
  'scripts/build-navigation.ts',
  'apps/web/src/game/Crops.ts',
  'Assets/bases/plantas.glb',
  'Assets/bases/terreno.glb',
])
  hash.update(fs.readFileSync(source));
for (const file of fs
  .readdirSync('Assets/bases')
  .filter((f) => /^base_.*\.glb$/.test(f))
  .sort()) {
  const id = file.slice(5, -4);
  const layout = JSON.parse(
    fs.readFileSync(`Assets/bases/base_${id}.json`, 'utf8'),
  ) as BaseFullLayout & { bay?: { crew: { path: number[][]; exit: number[] } } };
  layout.id = id;
  hash.update(fs.readFileSync(`Assets/bases/${file}`));
  hash.update(fs.readFileSync(`Assets/bases/base_${id}.json`));
  const model = readGeometry(`Assets/bases/${file}`);
  const transform = mapTransform(layout.bounds);
  model.position.set(transform.x, transform.y, transform.z);
  model.scale.setScalar(transform.scale);
  model.updateMatrixWorld(true);
  const crops = new CropSystem(model, plants, () => {});
  const grid = new BaseGrid(layout);
  const ship = new THREE.Vector3();
  let found = false;
  model.traverse((o) => {
    if (o.name.endsWith('_Nave')) {
      o.getWorldPosition(ship);
      found = true;
    }
  });
  if (!found) ship.copy(grid.getPadWorldPosition());
  const angle = Math.atan2(-ship.z, -ship.x);
  const raw = new THREE.Vector3(
    ship.x + Math.cos(angle) * 6.4,
    0.04,
    ship.z + Math.sin(angle) * 6.4,
  );
  const crew = layout.bay?.crew;
  let park = {
    x: ship.x + Math.cos(Math.atan2(ship.z, ship.x) + 1.2) * 9,
    z: ship.z + Math.sin(Math.atan2(ship.z, ship.x) + 1.2) * 9,
    h: 0,
  };
  if (crew?.path.length) {
    const door = crew.path[crew.path.length - 1]!;
    const w = grid.modelMetersToWorld(
      door[0]! + crew.exit[0]! * 6.5,
      door[1]! + crew.exit[1]! * 6.5,
    );
    park = { x: w.wx, z: w.wz, h: Math.atan2(crew.exit[0]!, -crew.exit[1]!) };
  }
  const rocks = terrain.getObjectByName('Rocas');
  grid.buildNavigation(model, {
    skip: (name) =>
      /_Telhado$|_Nave$|_Folha(Inf|Sup)$|_Antena_Prato$|_Pad(Luz)?_\d+$|_Rampa$/.test(name),
    extraObstacles: rocks ? [rocks] : [],
    seed: raw,
    vehicleSeed: new THREE.Vector3(park.x, 0, park.z),
  });
  const freePark = grid.nearestWalkablePoint(park.x, park.z, 40, 'vehicle');
  if (freePark) {
    park.x = freePark.x;
    park.z = freePark.z;
  }
  const spawns: { x: number; z: number; h: number }[] = [];
  for (let slot = 0; slot < 4; slot++) {
    let chosen: THREE.Vector3 | null = null;
    for (const r of [6.4, 7.6, 5.4, 9]) {
      for (let k = 0; k < 28 && !chosen; k++) {
        const a = angle + (k % 2 ? 1 : -1) * Math.ceil(k / 2) * 0.24;
        const x = ship.x + Math.cos(a) * r,
          z = ship.z + Math.sin(a) * r;
        if (!grid.isWalkable(x, z)) continue;
        if (
          Array.from({ length: 8 }, (_, j) => (j * Math.PI) / 4).some(
            (b) => !grid.isWalkable(x + Math.cos(b) * 0.9, z + Math.sin(b) * 0.9),
          )
        )
          continue;
        if (spawns.some((p) => Math.hypot(p.x - x, p.z - z) < 1.5)) continue;
        chosen = new THREE.Vector3(x, 0, z);
      }
      if (chosen) break;
    }
    chosen ??= grid.nearestWalkablePoint(ship.x, ship.z + 6, 60);
    if (!chosen) throw new Error(`${id}: no spawn`);
    spawns.push({ x: chosen.x, z: chosen.z, h: Math.atan2(-chosen.x, -chosen.z) });
  }
  const room =
    layout.rooms.find((r) => /medicina/i.test(r.kind)) ??
    layout.rooms.find((r) => /habitacao/i.test(r.kind)) ??
    layout.rooms[0];
  const center = room
    ? grid.tileToWorld(room.tile[0] + (room.size[0] - 1) / 2, room.tile[1] + (room.size[1] - 1) / 2)
    : { wx: 0, wz: 0 };
  const infirmary = grid.nearestWalkablePoint(center.wx, center.wz, 60);
  bases[id] = {
    layout,
    masks: grid.exportMasks(),
    spawns,
    park,
    infirmary,
    ship: { x: ship.x, z: ship.z },
  };
  crops.dispose();
  grid.dispose();
  console.log(`${id}: navigation + 4 spawns`);
}
const output = `/** Generated by scripts/build-navigation.ts. Do not edit. */\nexport const NAVIGATION_HASH = '${hash.digest('hex')}';\nexport const NAVIGATION_DATA = ${JSON.stringify(bases)};\n`;
const target = 'packages/shared/src/navigationData.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output)
    throw new Error('Navigation data is stale; run npm run navigation:build');
} else fs.writeFileSync(target, output);
