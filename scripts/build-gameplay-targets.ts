import fs from 'node:fs';
import * as THREE from 'three';
import { mapTransform } from '../packages/shared/src/navigation';
import { navigationData, navigationFor } from '../packages/shared/src/movement';
import { CropSystem } from '../apps/web/src/game/Crops';
import { LifeSupportStations } from '../apps/web/src/game/LifeSupportStations';
import { stationRoomIndex, type StationSite } from '../packages/sim/src/missions';
import { readGeometry } from './read-geometry';
const result: Record<string,unknown>={};
for(const id of ['arcadia','elysium','gale','hellas','jezero','olympus','utopia','valles']) {
  const data=navigationData(id),grid=navigationFor(id),layout=data.layout;
  const model=readGeometry(`Assets/bases/base_${id}.glb`),t=mapTransform(layout.bounds);
  model.position.set(t.x,t.y,t.z);model.scale.setScalar(t.scale);model.updateMatrixWorld(true);
  const crops=new CropSystem(model,null,()=>{}),life=new LifeSupportStations();
  life.setup(model,grid);
  const points:Record<string,{x:number;z:number}>={};
  const pos=(o:THREE.Object3D)=>{const p=o.getWorldPosition(new THREE.Vector3());return {x:p.x,z:p.z};};
  const filters:THREE.Object3D[]=[];let bench=0;
  model.traverse(o=> {
    if(/_FiltroAr_0[12]$/.test(o.name))filters.push(o);
    if(/_Sonda$/.test(o.name))points.drill=pos(o);
    if(/_BancadaFerramentas_d+$/.test(o.name))points[`bench:${bench++}`]=pos(o);
  });
  filters.sort((a,b)=>a.name.localeCompare(b.name)).slice(0,2).forEach((o,i)=>points[`filter:${i}`]=pos(o));
  crops.slots.forEach((s,i)=>points[`crop:${i}`]={x:s.world.x,z:s.world.z});
  if(crops.slots[0])points.garden=points['crop:0']!;
  if(life.oxygenPos)points.moxie={x:life.oxygenPos.x,z:life.oxygenPos.z};
  if(life.waterPos)points.water={x:life.waterPos.x,z:life.waterPos.z};
  // Match the visual station marker placement exactly.
  const taken:number[]=[],perRoom=new Map<number,number>();
  for(const site of ['lab','comms','power','medical','upload'] as StationSite[]) {
    const idx=stationRoomIndex(layout.rooms,site,taken),room=layout.rooms[idx]!;taken.push(idx);
    const a=grid.tileToWorld(room.tile[0],room.tile[1]),b=grid.tileToWorld(room.tile[0]+room.size[0]-1,room.tile[1]+room.size[1]-1);
    const n=perRoom.get(idx)??0;perRoom.set(idx,n+1);
    const x=(a.wx+b.wx)/2+n*1.3,z=(a.wz+b.wz)/2;
    const p=grid.nearestWalkablePoint(x,z,6);points[`station:${site}`]={x:p?.x??x,z:p?.z??z};
  }
  // Solar panel order matches BaseViewer's name sort.
  const panels:THREE.Object3D[]=[];
  model.traverse(o=>{if((o as THREE.Mesh).isMesh && ((o as THREE.Mesh).material as THREE.Material).name === 'M_Solar_Poeira')panels.push(o);});
  panels.forEach((o,i)=>points[`solar:${i}`]=pos(o));
  const a0=Math.atan2(data.park.z,data.park.x);
  outer:for(const dist of [38,32,44])for(const off of [0,.5,-.5,1,-1]) {
    const far=grid.nearestWalkablePoint(Math.cos(a0+off)*dist,Math.sin(a0+off)*dist,6,'vehicle');
    if(!far||Math.hypot(far.x,far.z)<26)continue;
    const {path}=grid.findPath(new THREE.Vector3(data.park.x,0,data.park.z),far,false,undefined,'vehicle');
    const end=path[path.length-1];if(end&&end.distanceTo(far)<4){points.soil={x:far.x,z:far.z};break outer;}
  }
  result[id]={points,crops:crops.stages(),solar:layout.solar?.map(()=>0)??[]};
  crops.dispose();life.dispose();
}
const text=`/** Generated by scripts/build-gameplay-targets.ts. */\nexport const GAMEPLAY_TARGETS = ${JSON.stringify(result,null,2)};\n`;
const path='packages/shared/src/gameplayTargets.ts';
if(process.argv.includes('--check')) {if(fs.readFileSync(path,'utf8')!==text)throw new Error('Gameplay targets are stale');}
else fs.writeFileSync(path,text);
